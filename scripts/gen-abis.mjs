// Regenerates packages/sdk/src/abis.ts from the Foundry build output (run `forge build` first).
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const names = ["CloakConfig", "CloakFactory", "CloakAuction", "CloakToken", "CloakPair", "CloakVesting", "CloakVestingDeployer", "ShieldedPool", "PrivateRouter", "PrivateBatcher", "CloakMigrator", "WHYPE"];
const extra = { Groth16Verifier: "Verifier.sol" }; // bytecode only
const fileOf = (n) => ({ CloakVestingDeployer: "CloakVesting.sol" })[n] ?? `${n}.sol`;
let out = "// Generated by scripts/gen-abis.mjs — do not edit.\n";
for (const n of names) {
  const { abi } = JSON.parse(readFileSync(`${root}contracts/out/${fileOf(n)}/${n}.json`, "utf8"));
  out += `\nexport const ${n === n.toUpperCase() ? n.toLowerCase() : n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(`${root}packages/sdk/src/abis.ts`, out);

// bytecode for deploy scripts / e2e
const bytecode = Object.fromEntries(
  names.map((n) => [n, JSON.parse(readFileSync(`${root}contracts/out/${fileOf(n)}/${n}.json`, "utf8")).bytecode.object]),
);
for (const [n, file] of Object.entries(extra)) {
  bytecode[n] = JSON.parse(readFileSync(`${root}contracts/out/${file}/${n}.json`, "utf8")).bytecode.object;
}
// circomlibjs Poseidon contracts (same constants as the circuit)
bytecode.Poseidon2 = readFileSync(`${root}contracts/test/fixtures/poseidon2.hex`, "utf8").trim();
bytecode.Poseidon3 = readFileSync(`${root}contracts/test/fixtures/poseidon3.hex`, "utf8").trim();
writeFileSync(`${root}packages/sdk/src/bytecode.ts`, `// Generated by scripts/gen-abis.mjs — do not edit.\nexport const bytecode = ${JSON.stringify(bytecode)} as const;\n`);
console.log("wrote abis.ts + bytecode.ts");
